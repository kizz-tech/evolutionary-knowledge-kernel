"""Application-owned boundaries for canonical storage and trusted runtime input."""
from datetime import datetime
from typing import Protocol

class Storage(Protocol):
    def initialize(self, files: dict[str, bytes]) -> dict: ...
    def snapshot(self, revision: str | None = None) -> dict: ...
    def history(self) -> list[str]: ...
    def apply(self, changes: dict[str, bytes | None], *, base: str,
              idempotency_key: str, principal: str, policy_digest: str) -> dict: ...
    def recover(self) -> list: ...
    def lookup(self, changes: dict[str, bytes | None], *, base: str,
               idempotency_key: str, principal: str, policy_digest: str) -> dict | None: ...

class Clock(Protocol):
    def now(self) -> datetime: ...

class Authority(Protocol):
    def principal(self) -> str: ...
